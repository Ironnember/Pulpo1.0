"""Envelope schema v2: dual-control signing and the policy veto registry.

Implements the signer-custody decision of 2026-11-27 (door-two close-out):
policy authority is held jointly -- two enrolled signer keys must both
sign every envelope, a third distinct key holds the policy-layer veto
(targeted kills are permanent and never delegate; a standing veto halts
all advances, carries a mandatory positive expiry, and is renewable), and
a fourth distinct key, the Operations Manager fallback, may perform
standing acts only after a chained request and 24 hours of veto-holder
silence. The veto holder's acts supersede fallback acts whenever they
land. A chain's era is fixed by its first recorded head: v1 chains verify
under v1 rules, and neither era silently converts to the other.

All keys are same-process synthetic test doubles, clearly labeled
test-only. Production keys are human-held, generated by their holders at
the genesis ceremony; no production or human key is exercised here.
"""

from __future__ import annotations

from dataclasses import replace
import unittest

from pulpo import (
    CeremonyTrust,
    DualControlTrust,
    EnvelopeSignature,
    GovernanceKernel,
    Intent,
    Policy,
    PolicyEnvelopeError,
    PolicyVetoError,
)
from pulpo.kernel import policy_hash_for
from pulpo.state import InMemoryKernelState
from tests.authority_support import (
    EnrolledHmacTestVerifier,
    HmacTestVerifier,
    dual_signed_policy_envelope,
    dual_trust_for,
    signed_policy_envelope,
    signed_policy_veto,
    trust_for,
)

NOW = 1_000_000_000_000
HOUR_NS = 3_600_000_000_000
SESSION = "policy-envelope-v2-proof-1"


class PolicyEnvelopeV2Tests(unittest.TestCase):
    def setUp(self):
        self.signer_a = EnrolledHmacTestVerifier("signer-key:test-a:v1", b"signer-a-test-secret")
        self.signer_b = EnrolledHmacTestVerifier("signer-key:test-b:v1", b"signer-b-test-secret")
        self.veto = EnrolledHmacTestVerifier("veto-key:test:v1", b"veto-test-secret")
        self.fallback = EnrolledHmacTestVerifier("fallback-key:test:v1", b"fallback-test-secret")
        self.trust = dual_trust_for(self.signer_a, self.signer_b, self.veto, self.fallback)
        self.policy = Policy(
            frozenset({"read", "push"}),
            100,
            dual_control_trust=self.trust,
        )
        self.envelope = dual_signed_policy_envelope(self.policy, self.signer_a, self.signer_b)
        self.intent = Intent("agent:publisher", "read", "repo:origin/main", 0, SESSION)
        self.now = [NOW]

    def make_kernel(self, *, policy=None, envelope=None, state=None, veto=False, fallback=False):
        return GovernanceKernel(
            policy or self.policy,
            clock=lambda: self.now[0],
            state=state,
            policy_envelope_v2=self.envelope if envelope is None else envelope,
            policy_signer_verifiers={
                self.signer_a.key_id: self.signer_a,
                self.signer_b.key_id: self.signer_b,
            },
            veto_verifier=self.veto if veto else None,
            fallback_verifier=self.fallback if fallback else None,
        )

    def bare_kernel(self, *, state=None):
        """A genesis dual-control kernel with no envelope (veto intake only)."""

        return GovernanceKernel(
            self.policy,
            clock=lambda: self.now[0],
            state=state,
            policy_signer_verifiers={
                self.signer_a.key_id: self.signer_a,
                self.signer_b.key_id: self.signer_b,
            },
            veto_verifier=self.veto,
            fallback_verifier=self.fallback,
        )

    def advance_policy(self, **changes):
        values = {
            "version": 2,
            "previous_policy_hash": policy_hash_for(self.policy),
        }
        values.update(changes)
        return replace(self.policy, **values)

    def veto_record(self, actor, kind, *, nonce, **fields):
        return signed_policy_veto(
            self.trust, actor, kind, now_ns=self.now[0], nonce=nonce, **fields
        )

    # -- Dual control ----------------------------------------------------

    def test_dual_signed_genesis_is_accepted_and_governs(self):
        kernel = self.make_kernel()
        head = kernel.policy_head
        self.assertEqual("pulpo.policy-envelope.v2", head["schema"])
        self.assertEqual(
            sorted([self.signer_a.key_id, self.signer_b.key_id]), head["signer_key_ids"]
        )
        self.assertEqual(self.veto.key_id, head["veto_key_id"])
        self.assertEqual("allow", kernel.evaluate(self.intent).outcome)
        heads = [r for r in kernel.audit if r["event"] == "policy_head_accepted"]
        self.assertEqual(1, len(heads))
        self.assertNotIn("signature", heads[0]["payload"])
        self.assertEqual(
            sorted([self.signer_a.key_id, self.signer_b.key_id]),
            heads[0]["payload"]["signer_key_ids"],
        )
        self.assertTrue(kernel.verify_audit())

    def test_dual_signed_advance_advances_the_head(self):
        state = InMemoryKernelState()
        self.make_kernel(state=state)
        policy_v2 = self.advance_policy()
        envelope_v2 = dual_signed_policy_envelope(policy_v2, self.signer_a, self.signer_b)
        second = self.make_kernel(policy=policy_v2, envelope=envelope_v2, state=state)
        self.assertEqual(2, second.policy_head["policy_version"])
        with self.assertRaisesRegex(PolicyEnvelopeError, "stale policy envelope"):
            self.make_kernel(state=state)

    def test_single_signature_envelope_is_refused(self):
        single = replace(
            self.envelope, signatures=(self.envelope.signatures[0],)
        )
        with self.assertRaisesRegex(PolicyEnvelopeError, "both enrolled signer keys"):
            self.make_kernel(envelope=single)

    def test_same_key_signing_twice_is_refused(self):
        entry = self.envelope.signatures[0]
        with self.assertRaisesRegex(ValueError, "must not repeat a signer key"):
            replace(self.envelope, signatures=(entry, entry))

    def test_unenrolled_key_signature_is_refused(self):
        rogue = EnvelopeSignature(key_id="signer-key:rogue", signature="00" * 64)
        tampered = replace(
            self.envelope, signatures=(self.envelope.signatures[0], rogue)
        )
        with self.assertRaisesRegex(PolicyEnvelopeError, "both enrolled signer keys"):
            self.make_kernel(envelope=tampered)

    def test_bad_signature_from_one_signer_is_refused(self):
        good, _ = self.envelope.signatures
        bad = EnvelopeSignature(key_id=self.signer_b.key_id, signature="00" * 64)
        tampered = replace(self.envelope, signatures=(good, bad))
        with self.assertRaisesRegex(PolicyEnvelopeError, "signature invalid"):
            self.make_kernel(envelope=tampered)

