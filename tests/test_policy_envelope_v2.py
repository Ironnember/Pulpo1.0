    # -- Targeted veto -----------------------------------------------------

    def test_targeted_veto_kills_an_envelope_permanently(self):
        state = InMemoryKernelState()
        kernel = self.make_kernel(state=state, veto=True)
        policy_v2 = self.advance_policy()
        envelope_v2 = dual_signed_policy_envelope(policy_v2, self.signer_a, self.signer_b)
        kernel.record_policy_veto(
            self.veto_record(
                self.veto, "targeted", nonce="t1", envelope_hash=envelope_v2.envelope_hash
            )
        )
        with self.assertRaisesRegex(PolicyEnvelopeError, "permanently vetoed"):
            self.make_kernel(policy=policy_v2, envelope=envelope_v2, state=state)
        # A standing veto that comes and goes changes nothing: the kill is
        # permanent and survives the standing veto's lapse.
        kernel.record_policy_veto(
            self.veto_record(
                self.veto, "standing", nonce="t2", expires_at_ns=self.now[0] + 1_000
            )
        )
        self.now[0] += 2_000
        with self.assertRaisesRegex(PolicyEnvelopeError, "permanently vetoed"):
            self.make_kernel(policy=policy_v2, envelope=envelope_v2, state=state)

    def test_targeted_veto_intake_refusals(self):
        kernel = self.bare_kernel()
        record = self.veto_record(
            self.veto, "targeted", nonce="t1", envelope_hash="a" * 64
        )
        tampered = replace(record, signature="00" * 64)
        with self.assertRaisesRegex(PolicyVetoError, "signature invalid"):
            kernel.record_policy_veto(tampered)
        kernel.record_policy_veto(record)
        with self.assertRaisesRegex(PolicyVetoError, "replayed"):
            kernel.record_policy_veto(record)
        duplicate = self.veto_record(
            self.veto, "targeted", nonce="t2", envelope_hash="a" * 64
        )
        with self.assertRaisesRegex(PolicyVetoError, "already under a targeted veto"):
            kernel.record_policy_veto(duplicate)

    # -- Standing veto -----------------------------------------------------

    def test_standing_veto_blocks_all_advances(self):
        state = InMemoryKernelState()
        kernel = self.make_kernel(state=state, veto=True)
        kernel.record_policy_veto(
            self.veto_record(
                self.veto, "standing", nonce="s1", expires_at_ns=self.now[0] + 10_000
            )
        )
        policy_v2 = self.advance_policy()
        envelope_v2 = dual_signed_policy_envelope(policy_v2, self.signer_a, self.signer_b)
        with self.assertRaisesRegex(PolicyEnvelopeError, "standing veto"):
            self.make_kernel(policy=policy_v2, envelope=envelope_v2, state=state)
        # Reopening the already-accepted head is a restart, not an advance.
        self.make_kernel(state=state)

